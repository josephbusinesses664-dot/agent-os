"""Built-in agent identities.

One structured identity per org-chart agent: an archetype (shared cognitive
pattern) plus a specialized overlay (mission, priorities, decision
framework, risk tolerance, autonomy, standards, styles).

Every field is consumed operationally:
- runtime prompt composition  (identity_prompt_block)
- model routing               (risk_tolerance / evidence standard)
- challenge protocol          (disagreement_style → structured challenges)

Role boundaries (no two agents own the same question) are encoded in each
mission. Autonomy levels L0–L5 shape what agents do without asking their
parent; they never override permissions, budgets or approval gates.
"""

from __future__ import annotations

from agentos.agents.identity import AgentIdentity  # noqa: F401 (re-export)
